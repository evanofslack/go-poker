var update = flag.Bool("update", false, "rewrite chart.go")

// TestChart checks the preflop charts rank hands sensibly. With -update it
// works them out again and rewrites chart.go, which takes a few seconds.
func TestChart(t *testing.T) {
	if *update {
		var b bytes.Buffer
		b.WriteString("// Code generated by go test ./bot -run TestChart -update. DO NOT EDIT.\n\npackage bot\n\n")
		b.WriteString("// The charts are each two card starting hand's percentile, in thousandths: ace to\n")
		b.WriteString("// deuce down and across, pairs on the diagonal, suited hands above it and offsuit\n")
		b.WriteString("// below. A hand at 900 is better than 90% of hands. Short deck has no 2s to 5s.\n")
		for _, c := range []struct {
			name string
			game holdem.Game
		}{{"fullChart", holdem.Game{}}, {"shortChart", holdem.Game{Short: true}}} {
			fmt.Fprintf(&b, "var %s = [13][13]int{\n", c.name)
			grid := chartOf(c.game, rand.New(rand.NewPCG(7, 7)))
			for _, row := range grid {
				b.WriteString("\t{")
				for j, v := range row {
					if j > 0 {
						b.WriteString(", ")
					}
					fmt.Fprintf(&b, "%3d", v)
				}
				b.WriteString("},\n")
			}
			b.WriteString("}\n\n")
		}
		src, err := format.Source(b.Bytes())
		must(t, err)
		must(t, os.WriteFile("chart.go", src, 0o644))
	}
	g := holdem.Game{}
	order := []string{"As Ad", "Ks Kd", "Qs Qd", "As Ks", "As Kd", "As Ts", "Ks Qd", "As 5s", "9s 8s", "2s 2d", "6s 7d", "7s 2d", "3s 2d"}
	for i := 1; i < len(order); i++ {
		a, b := cards(order[i-1][:2], order[i-1][3:]), cards(order[i][:2], order[i][3:])
		if percentile(g, a) <= percentile(g, b) {
			t.Errorf("%s (%.3f) should rank above %s (%.3f)", order[i-1], percentile(g, a), order[i], percentile(g, b))
		}
	}
	if p := percentile(g, cards("3d", "2c")); p > 0.01 {
		t.Errorf("three deuce: %.3f", p)
	}
	short := holdem.Game{Short: true}
	if percentile(short, cards("As", "Ad")) < 0.99 || percentile(short, cards("6s", "7d")) > 0.05 {
		t.Error("short deck chart is off")
	}
}

// chartOf works out every two card class's percentile in g, counting each
// class by its number of combinations, on a 13 by 13 grid.
func chartOf(g holdem.Game, r *rand.Rand) [13][13]int {
	type class struct {
		hi, lo int
		suited bool
		hole   []eval.Card
		combos int
		value  float64
	}
	byKey := map[[3]int]*class{}
	var classes []*class
	deck := holdem.Deck(g)
	for i, a := range deck {
		for _, b := range deck[i+1:] {
			hi, lo, suited := classOf([]eval.Card{a, b})
			k := [3]int{hi, lo, b2i(suited)}
			c, ok := byKey[k]
			if !ok {
				c = &class{hi: hi, lo: lo, suited: suited, hole: []eval.Card{a, b}}
				byKey[k] = c
				classes = append(classes, c)
			}
			c.combos++
		}
	}
	total := 0
	for _, c := range classes {
		// heads up and four way, scaled so each counts about the same
		c.value = equity(g, c.hole, nil, 1, anyHand, 0, 6000, r) + 2*equity(g, c.hole, nil, 3, anyHand, 0, 4000, r)
		total += c.combos
	}
	slices.SortFunc(classes, func(a, b *class) int {
		switch {
		case a.value < b.value:
			return -1
		case a.value > b.value:
			return 1
		}
		return 0
	})
	var grid [13][13]int
	below := 0
	for _, c := range classes {
		row, col := 12-c.hi, 12-c.lo
		if !c.suited {
			row, col = col, row
		}
		grid[row][col] = int((float64(below) + float64(c.combos)/2) / float64(total) * 1000)
		below += c.combos
	}
	return grid
}
